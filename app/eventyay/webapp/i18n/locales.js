const LOCALE_CODE_ALIASES = {
	ua: 'uk',
	ja: 'ja-jp',
	fa: 'fa-ir',
	pt_br: 'pt-br',
	zh_hans: 'zh-hans',
	zh_hant: 'zh-hant',
	de_informal: 'de',
	nl_informal: 'nl-informal',
	pl_informal: 'pl-informal',
	de_formal: 'de-formal',
	nb_no: 'nb-no',
}

export function normalizeLanguageCode(code) {
	if (!code) return ''
	const normalized = String(code).replaceAll('_', '-').toLowerCase()
	return LOCALE_CODE_ALIASES[normalized.replaceAll('-', '_')] || normalized
}

export function getLanguageNativeLabel(code) {
	if (!code) return ''
	const target = normalizeLanguageCode(code)
	const matched = locales.find(l => {
		const c = normalizeLanguageCode(l.code)
		return c === target || l.code.toLowerCase() === target
	})
	if (matched) return matched.nativeLabel
	const base = target.split('-')[0]
	const baseMatch = locales.find(l => l.code.toLowerCase() === base)
	if (baseMatch) return baseMatch.nativeLabel
	try {
		return new Intl.DisplayNames([code], { type: 'language' }).of(code) || code
	} catch {
		return code
	}
}

export function resolveLanguageOptions(configLocales) {
	if (Array.isArray(configLocales) && configLocales.length > 0 && typeof configLocales[0] === 'object') {
		return configLocales.map(item => ({
			code: item.code,
			label: item.label || item.nativeLabel || item.code,
			nativeLabel: item.nativeLabel || item.label || item.code,
			englishLabel: item.englishLabel || item.nativeLabel || item.label || item.code,
		}))
	}
	if (Array.isArray(configLocales) && configLocales.length > 0 && typeof configLocales[0] === 'string') {
		const wanted = new Set(configLocales.map(code => normalizeLanguageCode(code)))
		const matched = locales.filter(locale => wanted.has(normalizeLanguageCode(locale.code)))
		return matched.length ? matched : locales
	}
	return locales
}

export function resolveCurrentLanguage(availableLanguages, preferredLanguage) {
	const langs = Array.isArray(availableLanguages) && availableLanguages.length > 0
		? availableLanguages
		: locales
	const raw = preferredLanguage || 'en'
	const candidate = normalizeLanguageCode(raw)

	// 1. Exact match (normalized)
	const exact = langs.find(l => l && l.code && normalizeLanguageCode(l.code) === candidate)
	if (exact) return exact.code

	// 2. Progressively shorter subtags (e.g. zh-hant-hk -> zh-hant)
	const parts = candidate.split('-')
	for (let i = parts.length - 1; i > 1; i--) {
		const subtag = parts.slice(0, i).join('-')
		const subtagMatch = langs.find(l => l && l.code && normalizeLanguageCode(l.code) === subtag)
		if (subtagMatch) return subtagMatch.code
	}

	// 3. Exact base language match
	const base = parts[0]
	const baseExact = langs.find(l => l && l.code && normalizeLanguageCode(l.code).split('-')[0] === base)
	if (baseExact) return baseExact.code

	// 4. Any variant starting with base prefix
	const prefixMatch = langs.find(l => l && l.code && normalizeLanguageCode(l.code).startsWith(`${base}-`))
	if (prefixMatch) return prefixMatch.code

	const en = langs.find(l => l && l.code && normalizeLanguageCode(l.code) === 'en')
	if (en) return en.code

	return langs[0]?.code || 'en'
}
